// The two demo sites (/try/social/, /try/shop/): one "verify age" button that
// runs a real check through the verification service, then the site's own
// answer. <body data-site="social|shop"> picks the site.

import { t } from '/verifier/i18n.js';
import { request } from '/verifier/flow.js';
import { stepStatuses } from '/verifier/steps.js';
import { siteOutcome, SITE_THRESHOLDS } from './site.js';
import { setupLang, el, node } from './common.js';

const site = document.body.dataset.site;
const threshold = SITE_THRESHOLDS[site];
const params = new URLSearchParams(location.search);
// The /try/ page passes the wallet the visitor chose; the verifier knows families.
const family = params.get('wallet') === 'inji' ? 'inji' : 'openid';

let current = null; // session id being polled
let outcome = null; // last siteOutcome
let lastResult = null;
const lang = setupLang(render);

function render() {
  el('back').href = `/try/?lang=${lang()}`;
  if (!outcome || outcome === 'waiting') return;
  const key = {
    allowed: `site.${site}.allowed`,
    refused: `site.${site}.refused`,
    declined: 'site.declined',
    expired: 'site.expired',
    failed: 'site.failed',
  }[outcome];
  const verdict = el('verdict');
  verdict.className = `verdict ${{ allowed: 'ok', refused: 'warn' }[outcome] || 'neutral'}`;
  el('verdict-title').textContent = t(lang(), key);
  renderLearned();
}

function renderLearned() {
  const show = outcome === 'allowed' || outcome === 'refused' || outcome === 'failed';
  el('learned').hidden = !show;
  if (!show) return;
  el('learned-lede').textContent = t(lang(), 'site.learnedLede', { t: threshold });
  el('requested').replaceChildren(node('span', 'chip', `ageOver${threshold}`));
  const other = threshold === 16 ? 'ageOver18' : 'ageOver16';
  el('not-asked').replaceChildren(
    ...[t(lang(), 'try.name'), t(lang(), 'try.dob'), other].map((x) => node('span', 'chip muted', x)),
  );
  const list = el('steps');
  list.replaceChildren();
  for (const { id, status } of stepStatuses(lastResult || {})) {
    const li = node('li', status);
    li.append(
      node('span', 'icon', status === 'ok' ? '✓' : status === 'fail' ? '✕' : ''),
      node('span', 'name', t(lang(), `step.${id}`)),
      node('span', 'state', t(lang(), `status.${status}`)),
    );
    list.append(li);
  }
}

async function start() {
  el('verify').disabled = true;
  outcome = null;
  el('result').hidden = true;
  const { status, body } = await request(
    fetch,
    `/api/verifier/sessions?threshold=${threshold}&wallet=${family}&site=${site}`,
    { method: 'POST' },
  );
  el('verify').disabled = false;
  if (status !== 201 || !body?.sessionId) {
    finish('failed', null);
    return;
  }
  current = body.sessionId;
  el('qr').innerHTML = body.qrSvg; // generated by the verifier service, as on /verifier/
  el('open-wallet').href = body.qrData;
  el('present').hidden = false;
  poll(current);
}

async function poll(id) {
  while (current === id) {
    await new Promise((r) => setTimeout(r, 2000));
    if (current !== id) return;
    const { status, body } = await request(fetch, `/api/verifier/sessions/${encodeURIComponent(id)}`);
    if (current !== id) return;
    const o = siteOutcome(status, body);
    if (o !== 'waiting') {
      finish(o, body);
      return;
    }
  }
}

function finish(o, body) {
  current = null;
  outcome = o;
  lastResult = body;
  el('present').hidden = true;
  el('result').hidden = false;
  render();
}

el('verify').addEventListener('click', start);
el('again').addEventListener('click', () => {
  current = null;
  outcome = null;
  el('result').hidden = true;
  el('present').hidden = true;
});
