/**
 * @param {string} lang
 * @param {string} key
 * @param {Record<string, string|number>} [params]
 * @returns {string}
 */
export function t(lang, key, params = {}) {
  const template = MESSAGES[lang]?.[key] ?? MESSAGES.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

/**
 * The page's language: ?lang=, then the stored choice, then the browser's
 * preferences by primary subtag (pt-BR → pt), then English.
 *
 * @param {{query?: string|null, stored?: string|null, browser?: readonly string[]}} sources
 * @returns {string}
 */
export function pickLang({ query, stored, browser = [] } = {}) {
  const candidates = [query, stored, ...browser].map((tag) =>
    typeof tag === 'string' ? tag.toLowerCase().split('-')[0] : '',
  );
  return candidates.find((tag) => LANGS.includes(tag)) || 'en';
}
